const createIcon = (name, icon, collection, category, tags) => {
    const prefix = collection === "Lucide" ? "Lu" : collection === "Feather" ? "Fi" : "Fa";

    return {
        id: `${collection.toLowerCase().replaceAll(" ", "-")}-${name.toLowerCase().replaceAll(" ", "-")}`,
        name,
        componentName:
            iconNameOverrides[`${collection}:${name}`] ||
            `${prefix}${name.replaceAll(" ", "")}`,
        icon,
        collection,
        category,
        packageName:
            collection === "Lucide"
                ? "react-icons/lu"
                : collection === "Feather"
                  ? "react-icons/fi"
                  : "react-icons/fa6",
        tags,
    };
};

